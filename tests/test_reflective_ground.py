"""NCR-001: actual bounded self-evaluation, two independent execution engines."""
from __future__ import annotations

import json
import unittest
from dataclasses import replace
from hashlib import sha256

from invariant_demo import grid
from navigable_compute.reflective_ground import (
    host_run, compile_task_program, compile_reflector, reflect,
    lit, arg, choice, primitive, call)
from navigable_compute.reflective_verify import reference_run, verify_reflection
from navigable_compute.reflective_wire import encode_reflection, decode_reflection
from navigable_compute.self_space import build_endogenous_processor
from navigable_compute.invariant_space import canonical
from navigable_compute.wire import _wrap


class ReflectiveGroundTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.machine=build_endogenous_processor(grid(5))
        cls.other=build_endogenous_processor(grid(3))

    def test_same_language_interpreter_is_plain_data_not_a_magic_eval_opcode(self):
        kernel=compile_reflector()
        self.assertEqual(tuple(n for n,_ in kernel),
                         ('lookup','evaluate_list','perform','evaluate','invoke','run'))
        self.assertNotIn('"eval"',json.dumps(kernel))
        self.assertEqual(len(kernel),6)
        # The evaluator itself is source-program data in the same language it
        # interprets. It may be quoted as input without converting to Python.
        self.assertEqual(reference_run((('main',lit(kernel)),),'main',(),())[0],kernel)

    def test_equivalence_at_all_three_reflection_depths(self):
        m=self.machine
        for word in [(),(0,),(1,2),(0,1,0,1),(2,0,1,3)]:
            for state in m.states[::7]:
                values=[]
                for depth in range(3):
                    record=reflect(m,word,state,depth=depth)
                    self.assertTrue(verify_reflection(m,record))
                    values.append(record['result_state'])
                self.assertEqual(values,[values[0]]*3)

    def test_second_level_really_interprets_the_first_interpreter_source(self):
        m=self.machine
        table=m.operators
        p=compile_task_program(m)
        evaluator=compile_reflector()
        data=((0,1,2),m.states.index(m.states[0]))
        original=reference_run(p,'main',data,table)[0]
        once=reference_run(evaluator,'run',(p,'main',data,table),table)[0]
        twice=reference_run(evaluator,'run',
                (evaluator,'run',(p,'main',data,table),table),table)[0]
        self.assertEqual(original,once)
        self.assertEqual(once,twice)

    def test_reflection_overhead_is_measured_not_concealed(self):
        m=self.machine
        records=[reflect(m,(0,1),m.states[0],depth=d) for d in range(3)]
        self.assertEqual([r['host_evaluation_steps'] for r in records],[27,1257,53344])
        self.assertTrue(all(r['direct_host_steps']==27 for r in records))

    def test_language_can_interpret_control_flow_calls_and_data(self):
        # Additional program, not generated by the task-program template.
        branch=choice(primitive('eq',arg(0),lit(3)),
                      call('id',primitive('first',lit(('yes',)))),
                      primitive('cons',lit('no'),lit(())))
        program=(('id',arg(0)),('choose',branch))
        evaluator=compile_reflector()
        for inp in (3,4):
            args=(inp,)
            d=reference_run(program,'choose',args,())[0]
            s=host_run(evaluator,'run',(program,'choose',args,()),())[0]
            r=reference_run(evaluator,'run',(evaluator,'run',
                 (program,'choose',args,()),()),())[0]
            self.assertEqual(d,s)
            self.assertEqual(s,r)

    def test_finite_vocabulary_comes_from_different_invariant_worlds(self):
        a,b=self.machine,self.other
        self.assertEqual((a.instruction_count,b.instruction_count),(29,4))
        r1=reflect(a,(1,2),a.states[0],depth=2)
        r2=reflect(b,(1,2),b.states[0],depth=2)
        self.assertNotEqual(r1['source_ground_sha256'],r2['source_ground_sha256'])
        self.assertEqual(r1['interpreter_program_sha256'],r2['interpreter_program_sha256'])
        self.assertTrue(verify_reflection(a,r1) and verify_reflection(b,r2))

    def test_normal_forms_are_valid_reflected_programs(self):
        m=self.machine
        for op in (0,1,3,17,28):
            word=tuple(m.generator_opcodes[s] for s in m.normal_forms[op])
            for state in m.states[::8]:
                record=reflect(m,word,state,depth=1)
                self.assertEqual(record['result_state'],m.execute_opcode(op,state))

    def test_bounded_canonical_receipt_survives_clean_roundtrip(self):
        m=self.machine
        rec=reflect(m,(1,2,3),m.states[0],depth=2)
        raw=encode_reflection(m,rec)
        self.assertEqual(decode_reflection(raw,m),rec)
        self.assertEqual(raw,encode_reflection(m,decode_reflection(raw,m)))
        with self.assertRaises(ValueError):
            decode_reflection(raw+b' ',m)
        with self.assertRaises(ValueError):
            decode_reflection(raw,self.other)

    def test_recomputed_hash_cannot_forge_result_cost_or_semantics(self):
        m=self.machine
        rec=reflect(m,(0,1,2),m.states[0],depth=2)
        for field,bad in [('result_state',999),('host_evaluation_steps',1),
                          ('source_operator_count',28),('direct_host_steps',0),
                          ('interpreter_program_sha256','0'*64),
                          ('claim','universal AI processor'),('reflection_depth',3),
                          ('word',[0,1,999])]:
            hostile={**rec,field:bad}
            self.assertFalse(verify_reflection(m,hostile),field)
            with self.assertRaises(ValueError):
                decode_reflection(_wrap('finite-self-interpreting-task-ground',hostile),m)

    def test_recomputed_algebra_digest_still_fails_trusted_origin_check(self):
        m=self.machine
        operations=list(m.operators)
        operations[1]=tuple(reversed(operations[1]))
        broken=replace(m,operators=tuple(operations))
        broken=replace(broken,digest=sha256(canonical(broken.encode())).hexdigest())
        with self.assertRaises(ValueError):
            reflect(broken,(),m.states[0])

    def test_low_fuel_and_invalid_input_refuse(self):
        m=self.machine
        with self.assertRaises(ValueError):
            reflect(m,(0,1,2),m.states[0],depth=2,fuel=200)
        for word in ((-1,),(29,),(True,),[1],tuple([1]*33)):
            with self.assertRaises((TypeError,ValueError)):
                reflect(m,word,m.states[0])
        with self.assertRaises(ValueError):
            reflect(m,(),999)
        for depth in (-1,3,True):
            with self.assertRaises(ValueError):
                reflect(m,(),m.states[0],depth=depth)

    def test_no_unqualified_eval_primitive_or_python_arbitrary_code(self):
        bad=(('main',primitive('eval',lit('print(1)'))),)
        for runner in (host_run,reference_run):
            with self.assertRaises(ValueError):
                runner(bad,'main',(),())
            with self.assertRaises(ValueError):
                runner((('main',arg(-1)),),'main',(4,),())
            with self.assertRaises(ValueError):
                runner((('main',choice(lit(1),lit('yes'),lit('no'))),),'main',(),())
            with self.assertRaises(ValueError):
                runner((('main',primitive('at',lit((1,2)),lit(-1))),),'main',(),())
            with self.assertRaises(ValueError):
                runner((('main',primitive('task',lit(-1),lit(0))),),'main',(),self.machine.operators)

    def test_a_source_that_calls_itself_does_not_bypass_fuel(self):
        source=(('main',call('main')),)
        with self.assertRaises(ValueError):
            host_run(source,'main',(),(),fuel=50)
        with self.assertRaises(ValueError):
            reference_run(source,'main',(),(),fuel=50)

    def test_semantics_dont_depend_on_program_fitting_a_trillion_clock(self):
        # This is reflection on a finite program, not a claim that a trillion
        # iterations were performed. Monoid navigation is the separate lane.
        m=self.machine
        a=reflect(m,(0,1),m.states[0],depth=2)
        state,_=m.repeat_program((0,1),10**100+173,m.states[0])
        self.assertIn(state,m.states)
        self.assertEqual(a['source_ground_sha256'],m.digest)

if __name__ == '__main__':unittest.main()
