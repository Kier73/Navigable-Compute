"""NCS-001: derive a finite executable algebra from an invariant-generated Ground.

This is NOT a universal interpreter and does not execute without a physical host.
It constructs the finite transformation monoid generated by canonical NCI-001
laws. Its instructions, program normal forms, multiplication and state action
are obtained from that Ground rather than being supplied as an ISA.
"""
from __future__ import annotations

from dataclasses import dataclass, replace
from hashlib import sha256
from typing import Iterable

from .invariant_space import (InvariantDescription, InvariantTransformationSpace,
                              canonical, construct_invariant_space,
                              navigate_invariant_instance)

SCHEMA = 'navigable-compute.endogenous-operator-algebra.v0.1'


class AlgebraBudgetExceeded(ValueError):
    """The selected law generators do not admit the requested exact budget."""


@dataclass(frozen=True)
class EndogenousProcessor:
    source: InvariantTransformationSpace
    generator_limit: int
    states: tuple[int, ...]
    generator_coordinates: tuple[int, ...]
    generator_opcodes: tuple[int, ...]
    operators: tuple[tuple[int, ...], ...]  # maps dense state index -> dense state index
    normal_forms: tuple[tuple[int, ...], ...]  # words over generator indices
    multiply: tuple[tuple[int, ...], ...]  # i*j = apply j THEN i
    digest: str

    @property
    def instruction_count(self) -> int:
        return len(self.operators)

    def encode(self) -> dict:
        return {
            'schema': SCHEMA, 'source': self.source.packet(),
            'generator_limit': self.generator_limit,
            'states': list(self.states),
            'generator_coordinates_decimal': [str(x) for x in self.generator_coordinates],
            'generator_opcodes': list(self.generator_opcodes),
            'operators': [list(f) for f in self.operators],
            'normal_forms': [list(w) for w in self.normal_forms],
            'multiplication': [list(row) for row in self.multiply],
            'claim': 'finite-closed-generated-semantic-ISA;mathematical-only;not-universal-host',
        }

    def packet(self) -> dict:
        return {**self.encode(), 'sha256': self.digest}

    def _check_state(self, state: int) -> int:
        if type(state) is not int:
            raise TypeError('state must be an exact integer')
        try:
            return self.states.index(state)
        except ValueError:
            raise ValueError('state outside qualified mathematical Ground') from None

    def program_opcode(self, word: tuple[int, ...]) -> int:
        """Interpret a program as an element of the processor's own algebra."""
        if type(word) is not tuple or len(word) > 65536:
            raise ValueError('program word must be a bounded tuple')
        opcode = 0  # identity; earlier instruction runs first
        for instruction in word:
            if type(instruction) is not int or not 0 <= instruction < len(self.generator_opcodes):
                raise ValueError('instruction not in task-generated vocabulary')
            opcode = self.multiply[self.generator_opcodes[instruction]][opcode]
        return opcode

    def execute(self, word: tuple[int, ...], state: int) -> int:
        opcode = self.program_opcode(word)
        return self.states[self.operators[opcode][self._check_state(state)]]

    def execute_opcode(self, opcode: int, state: int) -> int:
        if type(opcode) is not int or not 0 <= opcode < self.instruction_count:
            raise ValueError('invalid task-generated macro instruction')
        return self.states[self.operators[opcode][self._check_state(state)]]

    def repeat_program(self, word: tuple[int, ...], repetitions: int, state: int) -> tuple[int, int]:
        """Evaluate word^repetitions using O(log repetitions) monoid products."""
        if type(repetitions) is not int or repetitions < 0 or repetitions.bit_length() > 4096:
            raise ValueError('invalid temporal coordinate')
        power = self.program_opcode(word)
        aggregate = 0
        count = 0
        while repetitions:
            if repetitions & 1:
                aggregate = self.multiply[power][aggregate]
                count += 1
            repetitions >>= 1
            if repetitions:
                power = self.multiply[power][power]
                count += 1
        return self.execute_opcode(aggregate, state), count

    def interpret_own_opcode(self, opcode: int, state: int) -> int:
        """Reconstruct any derived instruction from its internal normal-form word."""
        if type(opcode) is not int or not 0 <= opcode < self.instruction_count:
            raise ValueError('unknown derived instruction')
        return self.execute(self.normal_forms[opcode], state)


def build_endogenous_processor(desc: InvariantDescription, *, generator_limit: int = 16,
                               max_operators: int = 1024) -> EndogenousProcessor:
    """Construct the entire closed operator algebra for the selected NCI laws.

    Generators are the first min(generator_limit,law_count) canonical NCI law
    coordinates, not an externally supplied opcode list. This builds the exact
    closure of THOSE laws only, not necessarily all admissible NCI laws.
    """
    if (not isinstance(desc, InvariantDescription) or
            type(generator_limit) is not int or not 1 <= generator_limit <= 32 or
            type(max_operators) is not int or not 2 <= max_operators <= 4096):
        raise ValueError('invalid exact algebra-construction contract')
    source = construct_invariant_space(desc)
    states = tuple(s for s, rank in enumerate(source.ranks) if rank >= 0)
    if not states:
        raise ValueError('Ground has no qualified states')
    dense = {s: i for i, s in enumerate(states)}
    coords = tuple(range(min(generator_limit, source.law_count)))
    generators = []
    for k in coords:
        law = navigate_invariant_instance(source, k)
        try:
            generators.append(tuple(dense[law.transition[s]] for s in states))
        except KeyError as ex:
            raise AssertionError('qualified state space is not transition-closed') from ex

    ident = tuple(range(len(states)))
    operators = [ident]
    forms = [()]
    index = {ident: 0}
    frontier = 0
    # BFS enumerates a canonical shortest-then-lexicographic program for each
    # distinct transformation. Every new program adds one generator on the left.
    while frontier < len(operators):
        previous = operators[frontier]
        for gen_index, g in enumerate(generators):
            new_map = tuple(g[previous[i]] for i in range(len(states)))
            if new_map not in index:
                if len(operators) >= max_operators:
                    raise AlgebraBudgetExceeded('closure exceeds exact operator budget')
                index[new_map] = len(operators)
                operators.append(new_map)
                forms.append(forms[frontier] + (gen_index,))
        frontier += 1
    generator_opcodes = tuple(index[g] for g in generators)
    multiplication = tuple(tuple(index[tuple(a[b[i]] for i in range(len(states)))]
                                 for b in operators) for a in operators)
    proto = EndogenousProcessor(source, generator_limit, states, coords, generator_opcodes,
                                tuple(operators), tuple(forms), multiplication, '')
    return replace(proto, digest=sha256(canonical(proto.encode())).hexdigest())
