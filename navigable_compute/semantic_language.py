"""NCR-003: derive a finite executable language from observer semantics.

Given an NCS-001 task-generated transformation monoid, and an observer's
initial states/output partition, compute the *coarsest two-sided monoid
congruence* preserving every observation in every program context.  Its
quotient is a task-generated language.  Cayley's left-regular action
is a faithful interpreter for its OWN program elements.  This is exact,
finite algebra, not an interpreter for arbitrary source ASTs and not a
physical realization independent of the host.
"""
from __future__ import annotations

from dataclasses import dataclass, replace
from hashlib import sha256

from .invariant_space import canonical
from .self_space import EndogenousProcessor
from .self_verify import verify_endogenous_processor

SCHEMA = 'navigable-compute.observer-derived-language.v0.1'


@dataclass(frozen=True)
class ObservationContract:
    """One admissible starting-state set and one output label per source state.

    Exact preservation is required for every finite preceding/following
    program context generated by the source machine, not only the supplied
    initial states at the unmodified initial coordinate.
    """
    initial: tuple[int, ...]                 # source state IDs, not dense indices
    outputs: tuple[str, ...]                # one observed label per dense state

    def check(self, machine: EndogenousProcessor) -> None:
        if (type(self.initial) is not tuple or not self.initial or
            len(self.initial) != len(set(self.initial)) or
            any(type(s) is not int or s not in machine.states for s in self.initial)):
            raise ValueError('initial states must be a distinct nonempty set of source states')
        if (type(self.outputs) is not tuple or len(self.outputs) != len(machine.states) or
            any(type(s) is not str or not s or len(s) > 128 for s in self.outputs)):
            raise ValueError('one nonempty string output is required for each source state')
        if self.initial != tuple(sorted(self.initial)):
            raise ValueError('initial state set must be canonical and sorted')

    def encode(self):
        return {'initial': list(self.initial), 'outputs': list(self.outputs)}


@dataclass(frozen=True)
class SemanticLanguage:
    source_sha256: str
    contract: ObservationContract
    classes: tuple[tuple[int, ...], ...]
    class_of: tuple[int, ...]
    multiplication: tuple[tuple[int, ...], ...]
    generator_codes: tuple[int, ...]
    normal_forms: tuple[tuple[int, ...], ...]
    regular_actions: tuple[tuple[int, ...], ...]
    refinements: int
    digest: str

    @property
    def instruction_count(self) -> int:
        return len(self.classes)

    @property
    def identity(self) -> int:
        return self.class_of[0]

    def encode(self) -> dict:
        return {
            'schema': SCHEMA,
            'source_sha256': self.source_sha256,
            'observation': self.contract.encode(),
            'classes': [list(g) for g in self.classes],
            'class_of': list(self.class_of),
            'multiplication': [list(row) for row in self.multiplication],
            'generator_codes': list(self.generator_codes),
            'normal_forms': [list(word) for word in self.normal_forms],
            'regular_actions': [list(row) for row in self.regular_actions],
            'refinements': self.refinements,
            'claim': 'exact-two-sided-context-congruence;regular-action;finite-only'
        }

    def packet(self):
        return {**self.encode(), 'sha256': self.digest}

    def word_code(self, word: tuple[int, ...]) -> int:
        """Interpret source generator words through the derived quotient."""
        if type(word) is not tuple or len(word) > 65536:
            raise ValueError('word must be a bounded tuple')
        accumulator = self.identity
        for symbol in word:
            if type(symbol) is not int or not 0 <= symbol < len(self.generator_codes):
                raise ValueError('unknown generator')
            accumulator = self.regular_actions[self.generator_codes[symbol]][accumulator]
        return accumulator

    def apply_code_to_code(self, operator_code: int, data_code: int) -> int:
        """The language's regular action: executing code on its own code states."""
        if (type(operator_code) is not int or type(data_code) is not int or
            not 0 <= operator_code < len(self.classes) or
            not 0 <= data_code < len(self.classes)):
            raise ValueError('code is outside the derived language')
        return self.regular_actions[operator_code][data_code]

    def observe(self, machine: EndogenousProcessor, word: tuple[int, ...], state: int) -> str:
        """Render a source-state observation using a representative of its code class."""
        if machine.digest != self.source_sha256 or type(state) is not int or state not in self.contract.initial:
            raise ValueError('source Ground/initial-observer state mismatch')
        q = self.word_code(word)
        representative = self.classes[q][0]
        idx = machine.states.index(state)
        return self.contract.outputs[machine.operators[representative][idx]]

    def power_code(self, word: tuple[int, ...], repetitions: int) -> tuple[int, int]:
        """Navigate to a distant program coordinate with binary powering."""
        if type(repetitions) is not int or repetitions < 0 or repetitions.bit_length() > 4096:
            raise ValueError('invalid logical coordinate')
        power = self.word_code(word)
        result = self.identity
        products = 0
        while repetitions:
            if repetitions & 1:
                result = self.apply_code_to_code(power, result)
                products += 1
            repetitions >>= 1
            if repetitions:
                power = self.apply_code_to_code(power, power)
                products += 1
        return result, products


def _canonical_partition(signatures):
    mapping = {}
    blocks = []
    class_of = []
    for i, key in enumerate(signatures):
        if key not in mapping:
            mapping[key] = len(blocks)
            blocks.append([])
        c = mapping[key]
        class_of.append(c)
        blocks[c].append(i)
    return tuple(tuple(block) for block in blocks), tuple(class_of)


def derive_semantic_language(machine: EndogenousProcessor,
                             contract: ObservationContract, *,
                             max_source_ops: int = 64) -> SemanticLanguage:
    """Construct coarsest context-preserving language, or refuse budget.

    The source monoid is already constructed by NCS. Refining only its
    contextual observation equivalence does not evade source discovery cost.
    """
    if (not isinstance(machine, EndogenousProcessor) or
            not verify_endogenous_processor(machine.source.description, machine)):
        raise ValueError('unqualified task-generated source processor')
    n = len(machine.operators)
    if type(max_source_ops) is not int or not 1 <= max_source_ops <= 128 or n > max_source_ops:
        raise ValueError('exceeds exact semantic-closure budget')
    if not isinstance(contract, ObservationContract):
        raise ValueError('missing observer contract')
    contract.check(machine)
    init = tuple(machine.states.index(s) for s in contract.initial)
    labels = contract.outputs
    base = tuple(tuple(labels[machine.operators[j][s]] for s in init) for j in range(n))
    _, classes = _canonical_partition(base)
    iterations = 0
    while True:
        # All left/right one-instruction contexts suffice at the stable
        # fixed point to prove preservation of all finite contexts.
        signatures = tuple((base[j],
            tuple(classes[machine.multiply[a][j]] for a in range(n)),
            tuple(classes[machine.multiply[j][b]] for b in range(n)))
            for j in range(n))
        blocks, upgraded = _canonical_partition(signatures)
        if upgraded == classes:
            break
        if len(blocks) <= len(set(classes)) or iterations >= n:
            raise AssertionError('partition did not refine monotonically')
        classes = upgraded
        iterations += 1
    blocks, _ = _canonical_partition(signatures)
    mul = tuple(tuple(classes[machine.multiply[block_a[0]][block_b[0]]]
                      for block_b in blocks) for block_a in blocks)
    generators = tuple(classes[g] for g in machine.generator_opcodes)
    identity = classes[0]
    normal_forms = {identity: ()}
    ordered = [identity]
    for code in ordered:
        for g, symbol in enumerate(generators):
            result = mul[symbol][code]
            if result not in normal_forms:
                normal_forms[result] = normal_forms[code] + (g,)
                ordered.append(result)
    if len(ordered) != len(blocks):
        raise AssertionError('unreachable quotient element')
    actions = tuple(tuple(mul[i][j] for j in range(len(blocks))) for i in range(len(blocks)))
    language = SemanticLanguage(machine.digest, contract, blocks, classes, mul, generators,
                                tuple(normal_forms[k] for k in range(len(blocks))),
                                actions, iterations, '')
    return replace(language, digest=sha256(canonical(language.encode())).hexdigest())
